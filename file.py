import os
from typing import List, Dict, Optional, Any

class FileManager:
    """文件管理器"""
    
    def save_article(self, date: str, text_objects: List[Dict[str, str]]) -> bool:
        """保存文章内容到文件"""
        try:
            # 确保目录存在
            os.makedirs(date, exist_ok=True)
            
            # 使用第一段作为文件名
            output_path = f"{date}/{text_objects[0]['text']}.docx"
            
            # 调用外部保存函数
            from saveToWord import save_to_word
            save_to_word(text_objects, output_path)
            
            return True
            
        except Exception as e:
            print(f"文件保存失败: {str(e)}")
            return False

